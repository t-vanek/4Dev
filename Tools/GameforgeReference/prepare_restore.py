"""Prepare a guarded level/HP migration from exact official IDs, names and singleton values.

Other combat attributes and EXP are retained and explicitly remain unverified.
Original attribute rows are preserved; restored monsters receive separate attribute rows.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import unicodedata


def normalize(value):
    return re.sub("[^a-z0-9]", "", unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode().lower())


SQL_HEADER = """-- Restore only independently published monster level and maximum HP.
-- Source: Gameforge/monster-restoration.json; generated by Tools/GameforgeReference/prepare_restore.py.
-- Exact public IDs and names must match the pinned local Gameforge client.
-- Original attributes are retained. EXP, damage, defence, drops and spawn positions are NOT verified here.
USE [TGame_gsp];
GO
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.TGAMEFORGEMONSTERRESTORE',N'U') IS NULL
    CREATE TABLE dbo.TGAMEFORGEMONSTERRESTORE (
        wMonID INT NOT NULL PRIMARY KEY,
        bOriginalLevel TINYINT NOT NULL,
        wOriginalAttr SMALLINT NOT NULL,
        dwOriginalHP INT NOT NULL,
        wReferenceAttr SMALLINT NOT NULL UNIQUE,
        bReferenceLevel TINYINT NOT NULL,
        dwReferenceHP INT NOT NULL,
        szSource NVARCHAR(512) COLLATE DATABASE_DEFAULT NOT NULL,
        szSourceSha256 CHAR(64) COLLATE DATABASE_DEFAULT NOT NULL,
        tApplied DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
    );

CREATE TABLE #GameforgeReference (
    wMonID INT PRIMARY KEY, bOriginalLevel TINYINT, wOriginalAttr SMALLINT, dwOriginalHP INT,
    wReferenceAttr SMALLINT, bReferenceLevel TINYINT, dwReferenceHP INT,
    szSource NVARCHAR(512) COLLATE DATABASE_DEFAULT, szSourceSha256 CHAR(64) COLLATE DATABASE_DEFAULT
);
INSERT #GameforgeReference VALUES
"""

SQL_FOOTER = """;

-- Reject a different baseline or an untracked edit rather than overwriting it.
IF EXISTS (
    SELECT 1 FROM #GameforgeReference r
    LEFT JOIN dbo.TMONSTERCHART m ON m.wID=r.wMonID
    LEFT JOIN dbo.TGAMEFORGEMONSTERRESTORE b ON b.wMonID=r.wMonID
    WHERE m.wID IS NULL
       OR (b.wMonID IS NULL AND (m.bLevel<>r.bOriginalLevel OR m.wMonAttr<>r.wOriginalAttr))
       OR (b.wMonID IS NOT NULL AND
          (m.bLevel<>r.bReferenceLevel OR m.wMonAttr<>r.wReferenceAttr
           OR b.bOriginalLevel<>r.bOriginalLevel OR b.wOriginalAttr<>r.wOriginalAttr
           OR b.dwOriginalHP<>r.dwOriginalHP OR b.wReferenceAttr<>r.wReferenceAttr
           OR b.bReferenceLevel<>r.bReferenceLevel OR b.dwReferenceHP<>r.dwReferenceHP
           OR b.szSource<>r.szSource OR b.szSourceSha256<>r.szSourceSha256))
) THROW 51000,'Monster reference restore: the local baseline or a previous restore has changed.',1;

IF EXISTS (
    SELECT 1 FROM #GameforgeReference r
    LEFT JOIN dbo.TMONATTRCHART a ON a.wID=r.wOriginalAttr AND a.bLevel=r.bOriginalLevel
    WHERE a.wID IS NULL OR a.dwMaxHP<>r.dwOriginalHP
) THROW 51000,'Monster reference restore: an original attribute row is missing or has changed.',1;

IF EXISTS (
    SELECT 1 FROM #GameforgeReference r JOIN dbo.TMONATTRCHART a ON a.wID=r.wReferenceAttr
    LEFT JOIN dbo.TGAMEFORGEMONSTERRESTORE b ON b.wMonID=r.wMonID
    WHERE b.wMonID IS NULL OR a.bLevel<>r.bReferenceLevel OR a.dwMaxHP<>r.dwReferenceHP
) THROW 51000,'Monster reference restore: a reserved attribute ID is already in use or has changed.',1;

SELECT r.* INTO #GameforgeApply FROM #GameforgeReference r
WHERE NOT EXISTS(SELECT 1 FROM dbo.TGAMEFORGEMONSTERRESTORE b WHERE b.wMonID=r.wMonID);

-- Clone the complete original row without guessing the meaning of unpublished combat columns.
-- The only changed columns are its internal ID, level key and the published maximum HP.
DECLARE @columns NVARCHAR(MAX),@values NVARCHAR(MAX),@sql NVARCHAR(MAX);
SELECT @columns=STUFF((SELECT N','+QUOTENAME(c.name)
    FROM sys.columns c WHERE c.object_id=OBJECT_ID(N'dbo.TMONATTRCHART') AND c.is_identity=0 AND c.is_computed=0
    ORDER BY c.column_id FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,1,N'');
SELECT @values=STUFF((SELECT N','+CASE c.name
           WHEN N'wID' THEN N'r.wReferenceAttr'
           WHEN N'bLevel' THEN N'r.bReferenceLevel'
           WHEN N'dwMaxHP' THEN N'r.dwReferenceHP'
           ELSE N'a.'+QUOTENAME(c.name) END
    FROM sys.columns c WHERE c.object_id=OBJECT_ID(N'dbo.TMONATTRCHART') AND c.is_identity=0 AND c.is_computed=0
    ORDER BY c.column_id FOR XML PATH(''),TYPE).value('.','nvarchar(max)'),1,1,N'');
SET @sql=N'INSERT dbo.TMONATTRCHART ('+@columns+N') SELECT '+@values+
    N' FROM #GameforgeApply r JOIN dbo.TMONATTRCHART a ON a.wID=r.wOriginalAttr AND a.bLevel=r.bOriginalLevel';
EXEC sys.sp_executesql @sql;

INSERT dbo.TGAMEFORGEMONSTERRESTORE
    (wMonID,bOriginalLevel,wOriginalAttr,dwOriginalHP,wReferenceAttr,bReferenceLevel,dwReferenceHP,szSource,szSourceSha256)
SELECT wMonID,bOriginalLevel,wOriginalAttr,dwOriginalHP,wReferenceAttr,bReferenceLevel,dwReferenceHP,szSource,szSourceSha256
FROM #GameforgeApply;

UPDATE m SET bLevel=r.bReferenceLevel,wMonAttr=r.wReferenceAttr
FROM dbo.TMONSTERCHART m JOIN #GameforgeApply r ON r.wMonID=m.wID;

IF EXISTS (
    SELECT 1 FROM #GameforgeReference r
    LEFT JOIN dbo.TMONSTERCHART m ON m.wID=r.wMonID
    LEFT JOIN dbo.TMONATTRCHART a ON a.wID=m.wMonAttr AND a.bLevel=m.bLevel
    WHERE m.bLevel<>r.bReferenceLevel OR m.wMonAttr<>r.wReferenceAttr OR a.wID IS NULL OR a.dwMaxHP<>r.dwReferenceHP
) THROW 51000,'Monster reference restore failed its postcondition.',1;

SELECT COUNT(*) AS NewlyRestoredMonsterLevelAndHp FROM #GameforgeApply;
DROP TABLE #GameforgeApply;
DROP TABLE #GameforgeReference;
COMMIT TRANSACTION;
GO
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audit", type=Path, required=True)
    parser.add_argument("--database", type=Path, required=True)
    parser.add_argument("--official-monsters", type=Path, required=True)
    parser.add_argument("--official-root", type=Path, required=True)
    parser.add_argument("--client-manifest", type=Path, required=True)
    parser.add_argument("--comparison-manifest", type=Path, required=True)
    parser.add_argument("--reference-output", type=Path, required=True)
    parser.add_argument("--sql-output", type=Path, required=True)
    args = parser.parse_args()
    audit = json.loads(args.audit.read_text(encoding="utf-8"))
    database = json.loads(args.database.read_text(encoding="utf-8-sig"))
    client = json.loads(args.client_manifest.read_text(encoding="utf-8"))
    comparison = json.loads(args.comparison_manifest.read_text(encoding="utf-8"))
    # The parsed name export must belong to this exact, independently pinned client TMon archive.
    expected_hash = next(row["sha256"] for row in client["files"] if row["path"].lower() == "tcd/tmon.tcd")
    import csv
    inventory = list(csv.DictReader((args.comparison_manifest.parent / "official-files.csv").open(encoding="utf-8-sig")))
    parsed_hash = next(row["sha256"] for row in inventory if row["path"].lower() == "tcd/tmon.tcd")
    actual_hash = hashlib.sha256((args.official_root / "Tcd/TMon.tcd").read_bytes()).hexdigest()
    if expected_hash != parsed_hash or expected_hash != actual_hash:
        raise ValueError("The parsed monster names do not belong to the selected client reference")
    if Path(comparison["official"]).resolve() != args.official_root.resolve():
        raise ValueError("The name export points at a different official installation")
    names = {int(row["id"]): row["texts"][-1] for row in json.loads(args.official_monsters.read_text(encoding="utf-8"))}
    attributes = {(row["wID"], row["bLevel"]): row for row in database["attributes"]}
    used = {row["wID"] for row in database["attributes"]}
    free = iter(n for n in range(30000, 32768) if n not in used)
    selected, skipped = [], []
    for row in audit["out_of_range"]:
        detail = row.get("official_details")
        reason = None
        if not detail or detail["health"][0] != detail["health"][1]:
            reason = "Public level or HP is a range; the individual template is ambiguous"
        elif row["id"] not in names or normalize(names[row["id"]]) != normalize(row["name"]):
            reason = "The name does not exactly match the pinned local client after accent normalization"
        elif (row["local_attr_id"], row["local_level"]) not in attributes:
            reason = "The original attribute row is missing"
        if reason:
            skipped.append({"id": row["id"], "name": row["name"], "reason": reason, "url": row["url"]})
            continue
        original = attributes[(row["local_attr_id"], row["local_level"])]
        selected.append({"id": row["id"], "name": names[row["id"]], "old_level": row["local_level"],
                         "old_attr": row["local_attr_id"], "old_hp": original["dwMaxHP"], "new_attr": next(free),
                         "level": detail["level"][0], "hp": detail["health"][0], "source": row["url"],
                         "source_sha256": detail["sha256"]})
    if not selected or not any(row["id"] == 243 for row in selected):
        raise ValueError("No valid correction set including the checked Moray example")
    document = {"source": audit["source"], "client_monster_sha256": expected_hash,
                "restored_fields": ["level", "maximum_hp"],
                "unverified_fields": ["experience", "damage", "defence", "mana", "drops", "spawns"],
                "corrections": selected, "skipped": skipped}
    args.reference_output.parent.mkdir(parents=True, exist_ok=True)
    with args.reference_output.open("x", encoding="utf-8") as stream:
        json.dump(document, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    values = []
    for row in selected:
        quoted = row["source"].replace("'", "''")
        values.append(f"({row['id']},{row['old_level']},{row['old_attr']},{row['old_hp']},{row['new_attr']},"
                      f"{row['level']},{row['hp']},N'{quoted}','{row['source_sha256']}')")
    with args.sql_output.open("x", encoding="utf-8") as stream:
        stream.write(SQL_HEADER + ",\n".join(values) + SQL_FOOTER)
    print(f"Prepared {len(selected)} exact level/HP corrections; deferred {len(skipped)} ambiguous records")


if __name__ == "__main__":
    main()
